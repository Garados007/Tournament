// Elm tests can't read files, so this turns tests/fixtures/<version>/*.json
// into the Elm module Generated.Fixtures before elm-test runs.

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "fixtures");
const output = path.join(__dirname, "Generated", "Fixtures.elm");

function elmString(text) {
    let result = "";
    for (const char of text) {
        const code = char.codePointAt(0);
        if (char === "\\") result += "\\\\";
        else if (char === '"') result += '\\"';
        else if (char === "\n") result += "\\n";
        else if (char === "\r") result += "\\r";
        else if (char === "\t") result += "\\t";
        else if (code < 0x20) result += "\\u{" + code.toString(16).padStart(4, "0") + "}";
        else result += char;
    }
    return '"' + result + '"';
}

const fixtures = fs
    .readdirSync(root)
    .filter((dir) => /^\d+$/.test(dir))
    .sort((a, b) => Number(a) - Number(b))
    .flatMap((dir) =>
        fs
            .readdirSync(path.join(root, dir))
            .filter((file) => file.endsWith(".json"))
            .sort()
            .map((file) => ({
                version: Number(dir),
                name: file,
                json: fs.readFileSync(path.join(root, dir, file), "utf8"),
            })),
    );

const entries = fixtures.map(
    (fixture) =>
        `{ version = ${fixture.version}, name = ${elmString(fixture.name)}, json = ${elmString(fixture.json)} }`,
);

const source = `module Generated.Fixtures exposing (Fixture, fixtures)

{-| Generated by tests/fixtures.js. Don't edit.
-}


type alias Fixture =
    { version : Int
    , name : String
    , json : String
    }


fixtures : List Fixture
fixtures =
    [ ${entries.join("\n    , ")}
    ]
`;

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, source);
